export function getGrammarUnit(unit: number): GrammarUnitInfo {
  const found = GRAMMAR_DATA_12_UNITS.find((u) => u.unit === unit);
  return found || GRAMMAR_DATA_12_UNITS[0];
}

export function getAllGrammarQuestions(): GrammarQuestion[] {
  return GRAMMAR_DATA_12_UNITS.flatMap((u) => u.questions);
}

export function getGrammarQuestionsByUnit(unit: number): GrammarQuestion[] {
  if (unit === 0) {
    return getAllGrammarQuestions();
  }
  const unitInfo = getGrammarUnit(unit);
  return unitInfo ? unitInfo.questions : [];
}
